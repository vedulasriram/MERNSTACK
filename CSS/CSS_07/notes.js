/*


    margin : space outside the container 
    border : a line that separate the margin & padding 
    padding : space inside the container 
    content : any form of data 

    ! margin , padding & border - add the in all 4 directions 



    box-sizing: content-box;
        >> height & width of content always remain same or constant that developer assign to the container , padding, margin & border will be add on

        total width = left margin + left border + left padding + actual width + right padding + right border + right margin 

        total height =  top margin + top border + top padding + actual height + bottom padding + bottom border + bottom margin 

    box-sizing: border-box;
        >> total / final width = the value that developer assign 
        >> total / final height = the value that developer assign 

        >>height & width of content varies based on the margin , border & padding values 



        box-sizing = border-box ; 
    */
